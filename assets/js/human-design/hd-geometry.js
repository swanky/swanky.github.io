const pt = (a) => `${a[0]},${a[1]}`;

// 整條通道的 SVG path d。
export function channelFullD(p) {
  return p.t === 'Q' ? `M${pt(p.s)} Q${pt(p.c)} ${pt(p.e)}` : `M${pt(p.s)} L${pt(p.e)}`;
}

// 把通道在 t=0.5 切兩半（直線取中點、貝茲用 De Casteljau）。
// 回傳 [較小閘門半段 d, 較大閘門半段 d]，對齊 ch.gates[0] / ch.gates[1]。
export function channelHalfDs(p) {
  if (p.t === 'L') {
    const m = [(p.s[0] + p.e[0]) / 2, (p.s[1] + p.e[1]) / 2];
    return [`M${pt(p.s)} L${pt(m)}`, `M${pt(m)} L${pt(p.e)}`];
  }
  const m = [0.25 * p.s[0] + 0.5 * p.c[0] + 0.25 * p.e[0], 0.25 * p.s[1] + 0.5 * p.c[1] + 0.25 * p.e[1]];
  const c1 = [(p.s[0] + p.c[0]) / 2, (p.s[1] + p.c[1]) / 2];
  const c2 = [(p.c[0] + p.e[0]) / 2, (p.c[1] + p.e[1]) / 2];
  return [`M${pt(p.s)} Q${pt(c1)} ${pt(m)}`, `M${pt(m)} Q${pt(c2)} ${pt(p.e)}`];
}

