// ── 工具函式 ──────────────────────────────────────────────────────

// 干支序號（0=甲子 … 59=癸亥）→ 天干序、地支序
export function ganOf(gz) { return ((gz % 10) + 10) % 10; }
export function zhiOf(gz) { return ((gz % 12) + 12) % 12; }
// 干支序號 → 名稱（如 40 → 甲辰）
export function gzName(gz) { return GAN[ganOf(gz)] + ZHI[zhiOf(gz)]; }
// 天干序 + 地支序 → 干支序號（0..59）；僅陰配陰、陽配陽有解，否則 -1
export function ganZhiToGz(g, z) {
  for (let i = 0; i < 60; i++) if (i % 10 === g && i % 12 === z) return i;
  return -1;
}

// 五虎遁：年干 → 寅月天干序。口訣「甲己丙寅、乙庚戊寅、丙辛庚寅、丁壬壬寅、戊癸甲寅」。
// 公式：寅月干 = (年干 × 2 + 2) mod 10
export function tigerStartGan(yearGan) { return (yearGan * 2 + 2) % 10; }

// 五鼠遁：日干 → 子時天干序。口訣「甲己甲子、乙庚丙子、丙辛戊子、丁壬庚子、戊癸壬子」。
// 公式：子時干 = (日干 × 2) mod 10
export function ratStartGan(dayGan) { return (dayGan * 2) % 10; }

// 五行相生：木→火→土→金→水→木（回被生者）
const SHENG = { 木: '火', 火: '土', 土: '金', 金: '水', 水: '木' };
// 五行相剋：木剋土、土剋水、水剋火、火剋金、金剋木（回被剋者）
const KE = { 木: '土', 土: '水', 水: '火', 火: '金', 金: '木' };

export function sheng(a) { return SHENG[a]; }   // a 生 ?
export function ke(a) { return KE[a]; }         // a 剋 ?
export function isSheng(a, b) { return SHENG[a] === b; }  // a 生 b？
export function isKe(a, b) { return KE[a] === b; }        // a 剋 b？
