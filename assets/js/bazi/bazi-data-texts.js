// 月支 → 季節（寅卯辰春、巳午未夏、申酉戌秋、亥子丑冬）
export function seasonOf(monthZhi) {
  if ([2, 3, 4].includes(monthZhi)) return '春';
  if ([5, 6, 7].includes(monthZhi)) return '夏';
  if ([8, 9, 10].includes(monthZhi)) return '秋';
  return '冬';
}

