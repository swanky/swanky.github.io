// 三爻卦 index → [下,中,上] 位元
export function trigramBits(idx) { return [idx & 1, (idx >> 1) & 1, (idx >> 2) & 1]; }

// 卦 → 六爻 [初..上]（下卦低三爻、上卦高三爻）
export function hexLines(hex) {
  return [...trigramBits(hex.lower), ...trigramBits(hex.upper)];
}

export const HEXAGRAMS = RAW.map(([no, name, upper, lower, oneLine]) => {
  const h = { no, name, upper, lower, oneLine };
  h.lines = hexLines(h);
  h.upperName = TRIGRAMS[upper].name;
  h.lowerName = TRIGRAMS[lower].name;
  h.symbol = TRIGRAMS[upper].symbol + TRIGRAMS[lower].symbol;
  return h;
});

// key = upper*8 + lower（0..63）→ hex，反查用
const BY_KEY = {};
for (const h of HEXAGRAMS) BY_KEY[h.upper * 8 + h.lower] = h;

// 六爻 [初..上] → 卦
export function linesToHex(lines) {
  const lower = lines[0] + lines[1] * 2 + lines[2] * 4;
  const upper = lines[3] + lines[4] * 2 + lines[5] * 4;
  return BY_KEY[upper * 8 + lower];
}

export function hexByNo(no) { return HEXAGRAMS[no - 1]; }
