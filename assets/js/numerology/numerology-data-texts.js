// 依生命靈數與生日數組出結構化文案。
export function buildProfile(lifePath, birthday) {
  const lp = NUM_TEXTS[lifePath] || null;
  const bd = NUM_TEXTS[birthday] || null;
  return {
    lifePath,
    birthday,
    keyword: lp ? lp.keyword : '',
    theme: lp ? lp.theme : '',
    strength: lp ? lp.strength : '',
    challenge: lp ? lp.challenge : '',
    reminder: lp ? lp.reminder : '',
    birthdayNote: bd ? `你的生日數是 ${birthday}（${bd.keyword}）：${bd.strength}` : '',
  };
}
